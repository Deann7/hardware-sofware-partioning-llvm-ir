// Generic testbench: compares one implementation variant against the software reference
// over several 64x64 test images. Variant chosen with -DV_MONO / -DV_MANUAL / -DV_ORIG /
// -DV_GEN / -DV_STREAM; kernel chosen by the include path (kcfg.h, op.h, ref.cpp).
#include <cstdio>
#include "kcfg.h"

namespace golden {
#include "ref.cpp"
}

#define N 64
typedef unsigned char img_t[N][N];

static void make_image(int id, img_t img) {
    unsigned int s = 12345u + 7919u * id;
    for (int y = 0; y < N; y++)
        for (int x = 0; x < N; x++) {
            s = s * 1103515245u + 12345u;
            unsigned char noise = (s >> 16) & 0xff;
            unsigned char v;
            if (id == 0) v = noise;                                   // random
            else if (id == 1) v = (unsigned char)((x * 4 + y * 2) & 0xff); // gradient
            else v = (((x / 8) + (y / 8)) & 1) ? 230 : (noise & 0x1f); // checker + noise
            img[y][x] = v;
        }
}

#if defined(V_MONO)
void K_REF(unsigned char input[64][64], unsigned char output[64][64]);
static void run_dut(img_t in, img_t out) { K_REF(in, out); }

#elif defined(V_MANUAL) || defined(V_ORIG)
#include "op.h"
#include "ap_int.h"
#define R (K_S / 2)
#if defined(V_MANUAL)
void K_MANUAL(ap_uint<8 * K_S * K_S> win, unsigned char *result);
#else
void sobel_hw_datapath(unsigned char window[3][3], unsigned char *result);
#endif
static void run_dut(img_t in, img_t out) {
    for (int y = 0; y < N; y++)
        for (int x = 0; x < N; x++) {
            if (y < R || y >= N - R || x < R || x >= N - R) { out[y][x] = 0; continue; }
            unsigned char r = 0;
#if defined(V_MANUAL)
            ap_uint<8 * K_S * K_S> w = 0;
            for (int j = 0; j < K_S; j++)
                for (int i = 0; i < K_S; i++)
                    w.range(8 * (j * K_S + i) + 7, 8 * (j * K_S + i)) = in[y + j - R][x + i - R];
            K_MANUAL(w, &r);
#else
            unsigned char w[3][3];
            for (int j = 0; j < 3; j++)
                for (int i = 0; i < 3; i++) w[j][i] = in[y + j - 1][x + i - 1];
            sobel_hw_datapath(w, &r);
#endif
            out[y][x] = r;
        }
}

#elif defined(V_GEN)
// Software driver generated by the LLVM pass (gathers the window and calls K_GEN).
#include "gen/driver.inc"

#elif defined(V_STREAM)
#include "hls_stream.h"
#include "ap_axi_sdata.h"
typedef ap_axiu<8, 0, 0, 0> axis8_t;
void K_STREAM(hls::stream<axis8_t> &in, hls::stream<axis8_t> &out);
static void run_dut(img_t in, img_t out) {
    hls::stream<axis8_t> si, so;
    for (int y = 0; y < N; y++)
        for (int x = 0; x < N; x++) {
            axis8_t p;
            p.data = in[y][x];
            p.keep = 1; p.strb = 1;
            p.last = (y == N - 1 && x == N - 1);
            si.write(p);
        }
    K_STREAM(si, so);
    for (int y = 0; y < N; y++)
        for (int x = 0; x < N; x++) out[y][x] = so.read().data;
}
#endif

int main() {
    static img_t in, ref, dut;
    int errors = 0;
    for (int id = 0; id < 3; id++) {
        make_image(id, in);
        golden::K_REF(in, ref);
        run_dut(in, dut);
        int e = 0;
        for (int y = 0; y < N; y++)
            for (int x = 0; x < N; x++)
                if (ref[y][x] != dut[y][x]) {
                    if (e < 5) printf("  mismatch img%d (%d,%d): ref=%d dut=%d\n", id, y, x, ref[y][x], dut[y][x]);
                    e++;
                }
        printf("image %d: %d mismatches\n", id, e);
        errors += e;
    }
    printf(errors ? "TEST FAILED\n" : "TEST PASSED (bit-exact vs software reference)\n");
    return errors ? 1 : 0;
}
